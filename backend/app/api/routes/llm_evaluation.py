# backend/app/api/routes/llm_evaluation.py
#
# Endpoints for the LLM Comparison Evaluation feature (Paper 2 research).
# Only accessible to users with is_researcher=True flag on their account.
# Uses the pre-generated JSON file at backend/app/data/llm_evaluation_scores.json
# as the source of letter data and automated scores (D1-D4).
# D5 (professional tone) scores are stored in the llm_evaluation_scores DB table.
#
# Endpoints:
#   GET  /evaluation/letters         - returns blind letters for current scorer
#   POST /evaluation/score           - saves one D5 score for the current scorer
#   GET  /evaluation/progress        - returns scoring progress for current scorer
#   GET  /evaluation/results         - final results with LLM identities (admin only)
#   GET  /evaluation/kappa           - Cohen's Kappa between the two scorers (admin only)

import json
import uuid
from datetime import datetime
from pathlib import Path
from typing import Optional

from fastapi import APIRouter, Depends, HTTPException, status
from pydantic import BaseModel
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select, and_

from app.core.dependencies import get_current_user, require_role
from app.db.database import get_db
from app.models.user import User
from app.models.llm_evaluation_score import LLMEvaluationScore
from app.core.logger import get_logger

logger = get_logger(__name__)

router = APIRouter(prefix="/evaluation", tags=["LLM Evaluation"])

# Path to the pre-generated evaluation JSON.
# Generated by backend/scripts/score_llm_comparison.py and placed in
# backend/app/data/ so it's baked into the Docker image at build time.
DATA_FILE = Path(__file__).parent.parent.parent / "data" / "llm_evaluation_scores.json"



def load_evaluation_data() -> dict:
    # Loads the evaluation JSON. Cached approach - reads from disk on every
    # call but the file is small (~2MB for 140 letters) and this is a
    # research-only endpoint with very low traffic.
    if not DATA_FILE.exists():
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Evaluation data file not found. Run score_llm_comparison.py first.",
        )
    try:
        with open(DATA_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception as e:
        logger.error(f"Failed to load evaluation data: {e}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to load evaluation data.",
        )


def require_researcher():
    # Dependency that checks is_researcher flag on the user.
    # Used instead of require_role() since this is a research flag,
    # not a role-based permission.
    async def researcher_check(current_user: User = Depends(get_current_user)) -> User:
        if not getattr(current_user, "is_researcher", False):
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail="Access denied. This feature is only available to research evaluators.",
            )
        return current_user
    return researcher_check


class SubmitScoreRequest(BaseModel):
    case_id: str
    label: str
    d5_professional_tone: int  # 0 or 1


@router.get("/letters", status_code=status.HTTP_200_OK)
async def get_blind_letters(
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(require_researcher()),
):
    # Returns all 140 blind letters for the current scorer.
    # Each letter includes:
    #   - case_id, label (A/B/C/D) - no LLM name
    #   - clinical context (scenario, confidence, OHTS)
    #   - the letter text
    #   - automated D1-D4 scores (already calculated)
    #   - whether this scorer has already scored this letter's D5

    try:
        data = load_evaluation_data()
        letters = data.get("letters", [])

        # Fetch this scorer's existing D5 scores from the DB
        result = await db.execute(
            select(LLMEvaluationScore).where(
                LLMEvaluationScore.scorer_user_id == current_user.user_id
            )
        )
        existing_scores = result.scalars().all()

        # Build a lookup: (case_id, label) -> d5 score
        scored_lookup = {
            (str(s.case_id), s.label): s.d5_professional_tone
            for s in existing_scores
        }

        # Add is_scored and d5_score to each letter, but NEVER add actual_llm
        # (the LLM identity must stay hidden during blind scoring)
        enriched = []
        for letter in letters:
            key = (letter["case_id"], letter["label"])
            d5 = scored_lookup.get(key)
            enriched.append({
                "case_id": letter["case_id"],
                "patient_code": letter["patient_code"],
                "scenario": letter["scenario"],
                "label": letter["label"],
                "ai_prediction": letter["ai_prediction"],
                "ai_confidence_score": letter["ai_confidence_score"],
                "ohts_score": letter["ohts_score"],
                "ohts_tier": letter["ohts_tier"],
                "referral_letter": letter["referral_letter"],
                "auto_completeness_score": letter["auto_completeness_score"],
                "d1_clinical_finding": letter["d1_clinical_finding"],
                "d2_referral_request": letter["d2_referral_request"],
                "d3_screening_disclaimer": letter["d3_screening_disclaimer"],
                "d4_no_hallucination": letter["d4_no_hallucination"],
                "auto_quality_score": letter["auto_quality_score"],
                "response_time_seconds": letter["response_time_seconds"],
                "total_tokens": letter["total_tokens"],
                "is_scored": d5 is not None,
                "d5_score": d5,
            })

        return {
            "total": len(enriched),
            "scored_count": sum(1 for l in enriched if l["is_scored"]),
            "letters": enriched,
        }

    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Failed to get blind letters: {e}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to load letters.",
        )


@router.post("/score", status_code=status.HTTP_200_OK)
async def submit_score(
    request: SubmitScoreRequest,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(require_researcher()),
):
    # Save or update the current scorer's D5 score for one letter.
    # Uses upsert pattern - safe to call multiple times for the same letter
    # (updates existing score if already submitted).

    try:
        if request.d5_professional_tone not in (0, 1):
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="d5_professional_tone must be 0 or 1.",
            )

        result = await db.execute(
            select(LLMEvaluationScore).where(
                and_(
                    LLMEvaluationScore.case_id == uuid.UUID(request.case_id),
                    LLMEvaluationScore.label == request.label,
                    LLMEvaluationScore.scorer_user_id == current_user.user_id,
                )
            )
        )
        existing = result.scalar_one_or_none()

        if existing:
            existing.d5_professional_tone = request.d5_professional_tone
            existing.scored_at = datetime.utcnow()
            logger.info(f"[evaluation] Updated D5 score | user={current_user.user_code} case={request.case_id} label={request.label} score={request.d5_professional_tone}")
        else:
            new_score = LLMEvaluationScore(
                case_id=uuid.UUID(request.case_id),
                label=request.label,
                scorer_user_id=current_user.user_id,
                d5_professional_tone=request.d5_professional_tone,
                scored_at=datetime.utcnow(),
            )
            db.add(new_score)
            logger.info(f"[evaluation] New D5 score | user={current_user.user_code} case={request.case_id} label={request.label} score={request.d5_professional_tone}")

        await db.commit()
        return {"message": "Score saved successfully."}

    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Failed to save score: {e}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to save score.",
        )


@router.get("/progress", status_code=status.HTTP_200_OK)
async def get_progress(
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(require_researcher()),
):
    # Returns scoring progress for the current user.
    try:
        result = await db.execute(
            select(LLMEvaluationScore).where(
                LLMEvaluationScore.scorer_user_id == current_user.user_id
            )
        )
        scores = result.scalars().all()
        return {
            "scorer": current_user.user_code,
            "scored": len(scores),
            "total": 140,
            "complete": len(scores) == 140,
        }
    except Exception as e:
        logger.error(f"Failed to get progress: {e}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to get progress.",
        )


@router.get("/results", status_code=status.HTTP_200_OK)
async def get_results(
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(require_role("admin")),
):
    # Returns full results with LLM identities revealed.
    # Admin only - never exposed during blind scoring phase.
    # Includes automated D1-D4 scores, both scorers' D5 scores,
    # and per-LLM aggregated stats.

    try:
        data = load_evaluation_data()
        letters = data.get("letters", [])
        summary_per_llm = data.get("summary_per_llm", {})

        # Fetch all D5 scores from DB
        result = await db.execute(select(LLMEvaluationScore))
        all_scores = result.scalars().all()

        # Build lookup: (case_id, label, user_id) -> d5 score
        d5_lookup = {}
        for s in all_scores:
            key = (str(s.case_id), s.label, str(s.scorer_user_id))
            d5_lookup[key] = s.d5_professional_tone

        # Get all scorer user_ids
        scorer_ids = list(set(str(s.scorer_user_id) for s in all_scores))

        # Fetch scorer user_codes for display
        scorer_codes = {}
        for scorer_id in scorer_ids:
            from app.models.user import User as UserModel
            res = await db.execute(
                select(UserModel).where(UserModel.user_id == uuid.UUID(scorer_id))
            )
            u = res.scalar_one_or_none()
            if u:
                scorer_codes[scorer_id] = u.user_code

        # Enrich letters with D5 scores and LLM identity
        enriched = []
        for letter in letters:
            case_id = letter["case_id"]
            label = letter["label"]

            d5_scores = {}
            for scorer_id in scorer_ids:
                key = (case_id, label, scorer_id)
                d5_scores[scorer_codes.get(scorer_id, scorer_id)] = d5_lookup.get(key)

            # Combined quality score - average of auto quality + mean of d5 scores
            d5_values = [v for v in d5_scores.values() if v is not None]
            d5_mean = sum(d5_values) / len(d5_values) if d5_values else None
            combined = round(letter["auto_quality_score"] + d5_mean, 3) if d5_mean is not None else None

            enriched.append({
                **letter,
                "d5_scores_by_scorer": d5_scores,
                "d5_mean": d5_mean,
                "combined_quality_score": combined,
            })

        # Recalculate per-LLM summary including D5
        llm_combined = {}
        for llm in data.get("meta", {}).get("llms", []):
            llm_letters = [l for l in enriched if l.get("actual_llm") == llm]
            d5_means = [l["d5_mean"] for l in llm_letters if l["d5_mean"] is not None]
            combined_scores = [l["combined_quality_score"] for l in llm_letters if l["combined_quality_score"] is not None]
            llm_combined[llm] = {
                **summary_per_llm.get(llm, {}),
                "d5_mean": round(sum(d5_means)/len(d5_means), 3) if d5_means else None,
                "combined_quality_mean": round(sum(combined_scores)/len(combined_scores), 3) if combined_scores else None,
            }

        return {
            "meta": data.get("meta", {}),
            "summary_per_llm": llm_combined,
            "letters": enriched,
        }

    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Failed to get results: {e}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to load results.",
        )


@router.get("/kappa", status_code=status.HTTP_200_OK)
async def get_cohen_kappa(
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(require_role("admin")),
):
    # Calculates Cohen's Kappa between the two scorers' D5 scores.
    # Only meaningful once both scorers have completed all 140 letters.
    # Admin only.

    try:
        result = await db.execute(select(LLMEvaluationScore))
        all_scores = result.scalars().all()

        # Group scores by (case_id, label) -> {scorer_id: score}
        from collections import defaultdict
        grouped = defaultdict(dict)
        for s in all_scores:
            grouped[(str(s.case_id), s.label)][str(s.scorer_user_id)] = s.d5_professional_tone

        # Only include letters scored by exactly 2 scorers
        scorer_ids = list(set(str(s.scorer_user_id) for s in all_scores))
        if len(scorer_ids) < 2:
            return {
                "kappa": None,
                "message": "Need at least 2 scorers to calculate Cohen's Kappa.",
                "scorer_count": len(scorer_ids),
            }

        scorer_a, scorer_b = scorer_ids[0], scorer_ids[1]
        paired = []
        for key, scores in grouped.items():
            if scorer_a in scores and scorer_b in scores:
                if scores[scorer_a] is not None and scores[scorer_b] is not None:
                    paired.append((scores[scorer_a], scores[scorer_b]))

        if not paired:
            return {"kappa": None, "message": "No paired scores found yet.", "paired_count": 0}

        # Calculate Cohen's Kappa manually (binary: 0 or 1)
        n = len(paired)
        agree = sum(1 for a, b in paired if a == b)
        p_o = agree / n  # observed agreement

        # Expected agreement by chance
        p_a1 = sum(1 for a, b in paired if a == 1) / n
        p_b1 = sum(1 for a, b in paired if b == 1) / n
        p_a0 = 1 - p_a1
        p_b0 = 1 - p_b1
        p_e = (p_a1 * p_b1) + (p_a0 * p_b0)

        kappa = round((p_o - p_e) / (1 - p_e), 4) if p_e != 1 else 1.0

        # Interpret kappa
        if kappa >= 0.81:
            interpretation = "Almost perfect agreement"
        elif kappa >= 0.61:
            interpretation = "Substantial agreement"
        elif kappa >= 0.41:
            interpretation = "Moderate agreement"
        elif kappa >= 0.21:
            interpretation = "Fair agreement"
        else:
            interpretation = "Slight agreement"

        return {
            "kappa": kappa,
            "interpretation": interpretation,
            "paired_count": n,
            "observed_agreement": round(p_o, 4),
            "expected_agreement": round(p_e, 4),
            "scorer_a": scorer_a,
            "scorer_b": scorer_b,
        }

    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Failed to calculate kappa: {e}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to calculate Cohen's Kappa.",
        )
